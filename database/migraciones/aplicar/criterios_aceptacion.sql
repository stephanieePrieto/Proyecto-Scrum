-- C6: criterios de aceptación individuales, conservando historias.criterios.
-- Ejecutar con psql -v ON_ERROR_STOP=1 -f ...
BEGIN;
CREATE TABLE IF NOT EXISTS public.criterios_aceptacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  historia_id INTEGER NOT NULL REFERENCES public.historias(id) ON DELETE CASCADE,
  posicion INTEGER NOT NULL CHECK (posicion > 0),
  descripcion TEXT NOT NULL CHECK (length(btrim(descripcion)) > 0),
  cumplido BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE(historia_id, posicion)
);
CREATE INDEX IF NOT EXISTS ix_criterios_aceptacion_historia ON public.criterios_aceptacion(historia_id);
-- Importa criterios históricos separados por saltos de línea. No duplica al reejecutar.
WITH lineas AS (
 SELECT h.id AS historia_id, btrim(l.linea) AS descripcion,
        row_number() OVER (PARTITION BY h.id ORDER BY l.ordinalidad)::integer AS posicion
 FROM public.historias h
 CROSS JOIN LATERAL regexp_split_to_table(coalesce(h.criterios,''), E'\\r?\\n') WITH ORDINALITY AS l(linea, ordinalidad)
 WHERE btrim(l.linea) <> ''
)
INSERT INTO public.criterios_aceptacion(historia_id, posicion, descripcion)
SELECT historia_id, posicion, descripcion FROM lineas
ON CONFLICT(historia_id, posicion) DO NOTHING;
COMMIT;
